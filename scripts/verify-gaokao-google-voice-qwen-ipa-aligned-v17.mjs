#!/usr/bin/env node

import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {existsSync, readFileSync, readdirSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const scratchRoot = path.join(root, '.scratch/gaokao-google-voice-qwen-ipa-aligned-v17')
const publicRoot = path.join(root, 'app/public/vocabulary-assets/gaokao-frequency-v1/audio/google-voice-qwen-ipa-aligned-v17')
const manifest = JSON.parse(readFileSync(path.join(scratchRoot, 'manifest.json'), 'utf8'))
const audit = JSON.parse(readFileSync(path.join(scratchRoot, 'pronunciation-audit-v17.json'), 'utf8'))
const v16Qa = JSON.parse(readFileSync(path.join(root, '.scratch/gaokao-google-voice-qwen-recovery-v16/owner-qa-summary-v16.json'), 'utf8'))
const expectedKeys = new Set(v16Qa.failed.map((entry) => `${entry.entryId}:${entry.accent}`))
assert.equal(expectedKeys.size, 14)
assert.equal(audit.entries.length, 14)
assert.equal(audit.counts.materialTargetCorrections, 3)
assert.equal(manifest.schemaVersion, 'gaokao-frequency-google-voice-qwen-ipa-aligned-v17')
assert.equal(manifest.status, 'private_local_candidates_pending_owner_qa')
assert.equal(manifest.formalAssetsChanged, false)
assert.equal(manifest.distribution, 'local_private_evaluation_only')
assert.equal(manifest.plannedCases, 14)
assert.equal(manifest.plannedCandidates, 28)
assert.equal(manifest.entries.length, 28)
assert.equal(manifest.failures.length, 0)
assert.equal(manifest.edgeProtection.activeSafetySeconds, 0.1)
assert.equal(manifest.edgeProtection.leadingZeroSeconds, 0.3)
assert.equal(manifest.edgeProtection.trailingZeroSeconds, 0.5)

const byCase = new Map()
const hashes = new Set()
for (const entry of manifest.entries) {
  const caseKey = `${entry.entryId}:${entry.accent}`
  assert.ok(expectedKeys.has(caseKey))
  assert.ok(['C17', 'P17'].includes(entry.candidateLabel))
  assert.match(entry.sourceUrl, /^https:\/\/dictionary\.cambridge\.org\//)
  assert.ok(entry.verifiedIpa.startsWith('/') && entry.verifiedIpa.endsWith('/'))
  assert.ok(entry.guideText)
  assert.ok(entry.stressSpelling)
  assert.equal(entry.generatedTargetText, entry.candidateLabel === 'C17' ? entry.canonicalText : entry.stressSpelling)
  assert.equal(entry.activeSafetySeconds, 0.1)
  const scratchPath = path.join(scratchRoot, entry.path)
  const publicPath = path.join(root, 'app/public', entry.publicPath)
  const googlePath = path.join(root, `app/public/vocabulary-assets/gaokao-frequency-v1/audio/original-word-repair-v5/${entry.accent}/${entry.entryId}.mp3`)
  assert.ok(existsSync(scratchPath))
  assert.ok(existsSync(publicPath))
  assert.ok(existsSync(googlePath))
  const bytes = readFileSync(scratchPath)
  assert.deepEqual(readFileSync(publicPath), bytes)
  assert.equal(createHash('sha256').update(bytes).digest('hex'), entry.sha256)
  assert.equal(entry.sampleRate, 24000)
  assert.equal(entry.channels, 1)
  assert.ok(entry.durationSeconds >= 0.75 && entry.durationSeconds <= 3.6)
  assert.ok(entry.activeDurationSeconds >= 0.24)
  assert.ok(entry.leadingSilenceSeconds >= 0.24)
  assert.ok(entry.trailingSilenceSeconds >= 0.4)
  assert.ok(entry.peak >= 0.02)
  assert.ok(entry.rawPeak >= 0.03)
  assert.ok(entry.rawRms >= 0.015)
  assert.ok(entry.rawActiveFrameFraction >= 0.08)
  hashes.add(entry.sha256)
  const labels = byCase.get(caseKey) ?? new Map()
  labels.set(entry.candidateLabel, entry)
  byCase.set(caseKey, labels)
}
assert.equal(byCase.size, 14)
for (const [caseKey, labels] of byCase) {
  assert.equal(labels.size, 2, `Expected C17/P17 pair for ${caseKey}`)
  assert.ok(labels.has('C17'))
  assert.ok(labels.has('P17'))
  assert.notEqual(labels.get('C17').sha256, labels.get('P17').sha256)
}
assert.equal(hashes.size, 28)
assert.equal(readdirSync(publicRoot).filter((name) => name.endsWith('.mp3')).length, 28)
assert.equal(byCase.get('gaokao-frequency-2766-download:american').get('C17').verifiedIpa, '/ˈdaʊn.loʊd/')
assert.equal(byCase.get('gaokao-frequency-2823-dolphin:american').get('C17').verifiedIpa, '/ˈdɑːl.fɪn/')
assert.equal(byCase.get('gaokao-frequency-2866-downstairs:american').get('C17').verifiedIpa, '/ˌdaʊnˈsterz/')

const qaPath = path.join(root, 'app/public/vocabulary-assets/gaokao-frequency-v1/qa/google-voice-qwen-ipa-aligned-owner-qa-v17.html')
assert.ok(existsSync(qaPath))
const html = readFileSync(qaPath, 'utf8')
assert.match(html, /14 条 IPA 对准返修｜V17/)
assert.match(html, /dolphin/)
assert.match(html, /gaokao-google-voice-qwen-ipa-aligned-owner-qa-v17/)
console.log('PASS Google-voice Qwen V17: 14 audited failures, 28 IPA-aligned candidates, 3 corrected targets')
