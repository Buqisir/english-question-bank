#!/usr/bin/env node

import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

import {
  runCanonicalImportPilotQaSession,
  startCanonicalImportPilotQaArtifactServer,
} from './lib/canonicalImportPilotQaArtifactServer.mjs'
import {
  canonicalImportPilotTamperRejectionMatrix,
  sealCanonicalImportPilotEvidenceStaging,
} from './lib/canonicalImportPilotEvidenceRoot.mjs'

const head = '0123456789abcdef0123456789abcdef01234567'
const projectRoot = path.resolve(import.meta.dirname, '..')
const repositoryRoot = mkdtempSync(
  path.join(tmpdir(), 'eqb-canonical-import-pilot-qa-server-'),
)
const artifactDir = path.join(
  repositoryRoot,
  '.scratch/paper-canonical-ticket-20-qa',
  head,
)
const expectedArtifacts = {
  studentPrintHtml: {
    fileName: 'print-student.html',
    contentType: 'text/html; charset=utf-8',
    bytes: Buffer.from('<!doctype html><title>Student Print</title>\n'),
  },
  teacherPrintHtml: {
    fileName: 'print-teacher.html',
    contentType: 'text/html; charset=utf-8',
    bytes: Buffer.from('<!doctype html><title>Teacher Print</title>\n'),
  },
  studentChromiumPdf: {
    fileName: 'print-student.pdf',
    contentType: 'application/pdf',
    bytes: Buffer.from('%PDF-1.7\nstudent\n'),
  },
  teacherChromiumPdf: {
    fileName: 'print-teacher.pdf',
    contentType: 'application/pdf',
    bytes: Buffer.from('%PDF-1.7\nteacher\n'),
  },
}

function sha256(bytes) {
  return `sha256:${createHash('sha256').update(bytes).digest('hex')}`
}

mkdirSync(artifactDir, { recursive: true })
for (const artifact of Object.values(expectedArtifacts)) {
  writeFileSync(path.join(artifactDir, artifact.fileName), artifact.bytes)
}
writeFileSync(
  path.join(artifactDir, 'HEAD.txt'),
  `${head}\n`,
)
writeFileSync(
  path.join(artifactDir, 'continuation-public-seam-ledger.json'),
  `${JSON.stringify({
    schemaVersion: 'continuation-public-seam-ledger-v1',
    expectedHead: head,
  }, null, 2)}\n`,
)
const renderedArtifactDigests = Object.fromEntries(
  Object.values(expectedArtifacts).map((artifact) => [
    artifact.fileName,
    sha256(readFileSync(path.join(artifactDir, artifact.fileName))).slice('sha256:'.length),
  ]),
)
writeFileSync(
  path.join(artifactDir, 'evidence.json'),
  `${JSON.stringify({
    schemaVersion: 'canonical-import-pilot-evidence-v2',
    head,
    continuationPublicSeamLedger: {
      path: 'continuation-public-seam-ledger.json',
      sha256: sha256(readFileSync(
        path.join(artifactDir, 'continuation-public-seam-ledger.json'),
      )),
      expectedHead: head,
      schemaVersion: 'continuation-public-seam-ledger-v1',
    },
    semanticObservationDigest: `sha256:${'a'.repeat(64)}`,
    tamperRejectionMatrix: canonicalImportPilotTamperRejectionMatrix,
    renderedArtifactDigests,
  }, null, 2)}\n`,
)
sealCanonicalImportPilotEvidenceStaging({
  rootDir: artifactDir,
  expectedHead: head,
})

let qaServer
try {
  qaServer = await startCanonicalImportPilotQaArtifactServer({
    repositoryRoot,
    head,
  })

  assert.equal(
    qaServer.artifactDir,
    artifactDir,
    'QA server binds the exact HEAD-scoped artifact directory',
  )
  for (const [artifactId, expected] of Object.entries(expectedArtifacts)) {
    const response = await fetch(qaServer.urls[artifactId])
    assert.equal(response.status, 200, `${artifactId} URL loads`)
    assert.equal(
      response.headers.get('content-type'),
      expected.contentType,
      `${artifactId} has the correct content type`,
    )
    assert.deepEqual(
      Buffer.from(await response.arrayBuffer()),
      expected.bytes,
      `${artifactId} serves the exact generated bytes`,
    )
  }

  const unknown = await fetch(`${qaServer.baseUrl}/not-an-artifact`)
  assert.equal(unknown.status, 404, 'unknown QA paths fail closed')
  const traversal = await fetch(
    `${qaServer.baseUrl}/qa-artifacts/${head}/%2e%2e%2fHEAD.txt`,
  )
  assert.equal(traversal.status, 404, 'encoded traversal paths fail closed')
  assert.equal(
    qaServer.isListening(),
    true,
    'QA artifact process remains alive after serving every owner-QA artifact',
  )
} finally {
  await qaServer?.close()
  rmSync(repositoryRoot, { recursive: true, force: true })
}

// The retained-service probe below launches the complete visual import pilot.
// Its gold locks macOS Songti/Heiti glyph metrics that Ubuntu cannot prove by
// substituting another CJK face. The platform-neutral QA server assertions
// above still ran; report the missing authority-font layer truthfully.
if (process.platform !== 'darwin') {
  console.log('SKIP canonical import visual pilot cleanup probe: macOS authority glyph faces unavailable')
  process.exit(2)
}

const startupFailure = spawn(process.execPath, [
  'scripts/verify-paper-canonical-import-pilot.mjs',
  '--actual-artifacts',
  '--qa-server',
  '--inject-qa-artifact-server-startup-failure',
], {
  cwd: projectRoot,
  stdio: ['ignore', 'pipe', 'pipe'],
})
let startupFailureOutput = ''
let cleanupProbesResolved = false
let resolveCleanupProbes
let rejectCleanupProbes
const cleanupProbesPromise = new Promise((resolve, reject) => {
  resolveCleanupProbes = resolve
  rejectCleanupProbes = reject
})
const startupFailureExit = new Promise((resolve) => {
  startupFailure.once('exit', (code, signal) => {
    if (!cleanupProbesResolved) {
      rejectCleanupProbes(new Error(
        `real QA pilot exited before exposing cleanup probes (${code}, ${
          signal
        }):\n${startupFailureOutput}`,
      ))
    }
    resolve({ code, signal })
  })
})
const cleanupProbeTimeout = setTimeout(() => {
  rejectCleanupProbes(new Error(
    `real QA pilot did not expose cleanup probes:\n${startupFailureOutput}`,
  ))
  startupFailure.kill('SIGKILL')
}, 300_000)
const captureStartupFailureOutput = (chunk) => {
  startupFailureOutput += chunk.toString()
  const cleanupProbeMatch = startupFailureOutput.match(
    /(?:^|\n)QA retained-service cleanup probes: ([^\n]+)\n/,
  )
  if (!cleanupProbesResolved && cleanupProbeMatch) {
    cleanupProbesResolved = true
    resolveCleanupProbes(JSON.parse(cleanupProbeMatch[1]))
  }
}
startupFailure.stdout.on('data', captureStartupFailureOutput)
startupFailure.stderr.on('data', captureStartupFailureOutput)
startupFailure.once('error', rejectCleanupProbes)

const cleanupProbes = await cleanupProbesPromise
assert.equal(
  startupFailure.exitCode,
  null,
  'real QA pilot remains alive before retained-service cleanup probes',
)
assert.equal(
  startupFailure.signalCode,
  null,
  'real QA pilot has not received an exit signal before cleanup probes',
)
let retainedServiceProbeError
try {
  for (const [service, url] of Object.entries(cleanupProbes)) {
    await assert.rejects(
      fetch(url, { signal: AbortSignal.timeout(2_000) }),
      `${service} is unreachable after artifact server startup failure`,
    )
  }
} catch (error) {
  retainedServiceProbeError = error
} finally {
  assert.equal(
    startupFailure.exitCode,
    null,
    'real QA pilot remains alive through retained-service cleanup probes',
  )
  assert.equal(
    startupFailure.signalCode,
    null,
    'real QA pilot receives no exit signal before cleanup probes finish',
  )
  startupFailure.kill('SIGTERM')
}
const startupFailureResult = await startupFailureExit
clearTimeout(cleanupProbeTimeout)
if (retainedServiceProbeError) throw retainedServiceProbeError
assert.notEqual(
  startupFailureResult.code,
  0,
  'injected artifact server startup failure rejects the real QA pilot',
)
assert.match(
  startupFailureOutput,
  /Injected QA artifact server startup failure/,
  'real QA pilot preserves the injected startup failure',
)

const closeError = new Error('injected QA artifact server close failure')
let closeFailureClosedRetainedServices = false
await assert.rejects(
  runCanonicalImportPilotQaSession({
    startArtifactServer: async () => ({
      close: async () => {
        throw closeError
      },
    }),
    artifactServerOptions: { repositoryRoot, head },
    closeRenderedServices: async () => {
      closeFailureClosedRetainedServices = true
    },
    run: async () => {},
  }),
  closeError,
)
assert.equal(
  closeFailureClosedRetainedServices,
  true,
  'artifact server close failure still closes retained API and Vite services',
)

console.log('PASS Ticket 20 HEAD-scoped QA artifact server')
