const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 }
const num = (n) => String(Number(n.toFixed(3)))
function growPath(d, k, [cx, cy], [tx, ty]) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/g) ?? []
  let out = ''
  let i = 0
  let cmd = ''
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) {
      cmd = tokens[i++]
      out += cmd
      if (cmd.toLowerCase() === 'z') continue
    } else if (cmd.toLowerCase() === 'm') cmd = cmd === 'm' ? 'l' : 'L'
    const lower = cmd.toLowerCase()
    // 路径开头的小写 m 相对于原点，等同绝对坐标。
    const rel = cmd === lower && !(i === 1 && lower === 'm')
    const v = tokens.slice(i, i + ARGS[lower]).map(Number)
    i += ARGS[lower]
    const X = (x) => (rel ? x * k : (x - cx) * k + tx)
    const Y = (y) => (rel ? y * k : (y - cy) * k + ty)
    let w
    if (lower === 'h') w = [X(v[0])]
    else if (lower === 'v') w = [Y(v[0])]
    else if (lower === 'a') w = [v[0] * k, v[1] * k, v[2], v[3], v[4], X(v[5]), Y(v[6])]
    else w = v.map((n, j) => (j % 2 ? Y(n) : X(n)))
    out += `${w.map((n, j) => (lower === 'a' && j >= 2 && j <= 4 ? String(n) : num(n))).join(' ')} `
  }
  return out.trim()
}
function grow(k, markup, c = [12, 12]) {
  const to = [12, 12]
  const X = (x) => num((x - c[0]) * k + to[0])
  const Y = (y) => num((y - c[1]) * k + to[1])
  const S = (s) => num(s * k)
  return markup.replace(/<(path|circle|rect)([^>]*)\/>/g, (_m, tag, attrs) => {
    const next = attrs.replace(/([\w-]+)="([^"]*)"/g, (all, name, value) => {
      if (tag === 'path' && name === 'd') return `d="${growPath(value, k, c, to)}"`
      if (name === 'cx' || name === 'x') return `${name}="${X(Number(value))}"`
      if (name === 'cy' || name === 'y') return `${name}="${Y(Number(value))}"`
      if (['r', 'rx', 'ry', 'width', 'height'].includes(name)) return `${name}="${S(Number(value))}"`
      return all
    })
    return `<${tag}${next}/>`
  })
}
