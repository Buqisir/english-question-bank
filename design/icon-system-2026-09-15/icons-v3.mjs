function pen({ tip: [tx, ty], length, width = 4.5, nib = 3 }) {
  const u = [Math.SQRT1_2, -Math.SQRT1_2]
  const n = [Math.SQRT1_2, Math.SQRT1_2]
  const r = width / 2
  const at = (d, s) => [tx + u[0] * d + n[0] * s, ty + u[1] * d + n[1] * s]
  const f = ([x, y]) => `${x.toFixed(2)} ${y.toFixed(2)}`
  return `<path d="M${f([tx, ty])}L${f(at(nib, -r))}L${f(at(length, -r))}A${r} ${r} 0 0 1 ${f(at(length, r))}L${f(at(nib, r))}Z"/>`
}

